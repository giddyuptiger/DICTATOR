    /// The tone options for a base emoji (the plain base plus five tones), or nil
    /// if it does not support skin tones.
    static func skinToneVariants(for base: String) -> [String]? {
        guard toneable.contains(base) else { return nil }
        return [base] + toneModifiers.map { base + $0 }
